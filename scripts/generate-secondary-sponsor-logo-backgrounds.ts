// Build-time metadata only: existing logo bitmaps are never rewritten.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { SPONSORS } from "../data/sponsors";

async function main() {
const backgrounds: Record<string, string> = {};
for (const sponsor of [...SPONSORS].sort((a, b) => a.logoPath.localeCompare(b.logoPath))) {
  const input = await readFile(path.join(process.cwd(), "public", sponsor.logoPath));
  const metadata = await sharp(input).metadata();
  if (metadata.hasAlpha) continue;
  const { data, info } = await sharp(input).resize(8, 8, { fit: "fill", kernel: "nearest" }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const offsets = [0, 7, 56, 63].map(index => index * info.channels);
  const background = [0, 1, 2].map(channel => Math.round(offsets.reduce((sum, offset) => sum + data[offset + channel], 0) / offsets.length));
  backgrounds[sponsor.logoPath] = "#" + background.map(value => value.toString(16).padStart(2, "0")).join("");
}
const source = `// Generated by scripts/generate-secondary-sponsor-logo-backgrounds.ts. No runtime image processing.\nconst backgrounds: Readonly<Record<string, string>> = ${JSON.stringify(backgrounds, null, 2)};\n\nexport function getSecondarySponsorLogoBackgroundColor(logoPath: string): string | undefined {\n  return backgrounds[logoPath];\n}\n`;
await writeFile("lib/game/secondary-sponsor-logo-backgrounds.ts", source);
console.log(JSON.stringify({ libraryLogos: SPONSORS.length, opaqueLogoBackgrounds: Object.keys(backgrounds).length }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
