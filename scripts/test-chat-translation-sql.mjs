const permissions = (await db.query("select has_function_privilege('authenticated','public.claim_global_chat_translation_batch(uuid,text,jsonb)','execute') as player, has_function_privilege('service_role','public.claim_global_chat_translation_batch(uuid,text,jsonb)','execute') as server")).rows[0];
